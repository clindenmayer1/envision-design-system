/*
 * Regenerates packages/tokens/src/tokens-table.md from the DTCG sources.
 *
 * The table was hand-maintained and had fallen behind the build: it listed 188 rows under a header
 * claiming 345, and advertised a `t3/button/outline` family that no token file defines. A table
 * nobody can regenerate is a table nobody can trust, so this makes it derived.
 */
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { tokenIndex } from './token-index.mjs';

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'packages/tokens/src/tokens-table.md');
const { rows } = tokenIndex();

const cell = (v) => (typeof v === 'object' ? JSON.stringify(v) : String(v));
const lines = [
  '# Envision - Machine-Readable Token Table',
  '',
  `Flattened from \`packages/tokens/src/*.tokens.json\` (DTCG). ${rows.length} token entries. CSS custom property = column \`css\`. Alias targets shown as \`{path}\`.`,
  '',
  'Generated by `node scripts/gen-token-table.mjs`. Do not edit by hand.',
  '',
  '| Tier | Token path | Type | Value / Alias | CSS variable |',
  '|---|---|---|---|---|',
  ...rows.map((r) => `| ${r.tier.toUpperCase()} | ${r.path} | ${r.type} | \`${cell(r.value)}\` | \`${r.css}\` |`),
  '',
];
writeFileSync(out, lines.join('\n'));
console.log(`tokens-table.md: ${rows.length} rows`);
